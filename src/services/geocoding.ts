// Asynchronous Geocoder with OpenStreetMap Nominatim Live API + Offline Fallback
export async function geocodeLocationPrecise(
  placeName: string = '',
  districtName: string = '',
  stateName: string = '',
  pinCode: string = ''
): Promise<[number, number]> {
  // Try online OpenStreetMap Nominatim if possible
  const query = [placeName, districtName, pinCode, stateName, 'India']
    .filter(Boolean)
    .join(', ');

  if (query.length > 5) {
    try {
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 1800);

      const response = await fetch(
        `https://nominatim.openstreetmap.org/search?format=json&q=${encodeURIComponent(query)}&countrycodes=in&limit=1`,
        {
          headers: {
            'Accept': 'application/json',
            'User-Agent': 'JanSetu-DPI-Platform/1.0'
          },
          signal: controller.signal
        }
      );
      clearTimeout(timeoutId);

      if (response.ok) {
        const data = await response.json();
        if (data && data.length > 0 && data[0].lat && data[0].lon) {
          const lat = parseFloat(data[0].lat);
          const lon = parseFloat(data[0].lon);
          if (!isNaN(lat) && !isNaN(lon)) {
            return [Number(lat.toFixed(6)), Number(lon.toFixed(6))];
          }
        }
      }
    } catch (e) {
      // Gracefully fall through to fast offline database
    }
  }

  // Fast offline fallback
  return resolvePreciseOfflineCoordinates(placeName, districtName, stateName, pinCode);
}

// Browser HTML5 Live GPS capture helper
export async function getLiveBrowserGps(): Promise<{
  coordinates: [number, number];
  accuracyMeters?: number;
  reverseDetails?: {
    district?: string;
    state?: string;
    suburb?: string;
    road?: string;
    postcode?: string;
  };
}> {
  return new Promise((resolve, reject) => {
    if (!navigator.geolocation) {
      reject(new Error('Geolocation is not supported by your browser'));
      return;
    }

    navigator.geolocation.getCurrentPosition(
      async (pos) => {
        const lat = Number(pos.coords.latitude.toFixed(6));
        const lng = Number(pos.coords.longitude.toFixed(6));
        const accuracy = Math.round(pos.coords.accuracy);

        let reverseDetails: any = {};
        try {
          // Attempt reverse geocoding
          const controller = new AbortController();
          const timeoutId = setTimeout(() => controller.abort(), 2000);
          const res = await fetch(
            `https://nominatim.openstreetmap.org/reverse?format=json&lat=${lat}&lon=${lng}&zoom=14&addressdetails=1`,
            { signal: controller.signal }
          );
          clearTimeout(timeoutId);
          if (res.ok) {
            const data = await res.json();
            if (data && data.address) {
              reverseDetails = {
                district: data.address.state_district || data.address.county || data.address.city,
                state: data.address.state,
                suburb: data.address.suburb || data.address.village || data.address.town || data.address.neighbourhood,
                road: data.address.road,
                postcode: data.address.postcode
              };
            }
          }
        } catch (e) {
          // ignore reverse geocoding errors
        }

        resolve({
          coordinates: [lat, lng],
          accuracyMeters: accuracy,
          reverseDetails
        });
      },
      (err) => {
        reject(err);
      },
      {
        enableHighAccuracy: true,
        timeout: 8000,
        maximumAge: 0
      }
    );
  });
}
